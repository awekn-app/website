/**
 * THE ARC'S PRECOMPUTE. Builds the arc's season (src/app/site/arc/season.ts, buildSeason) and solves
 * its annotation layout (src/app/site/arc/annotate.ts) here in Node, then writes both answers as
 * constants the page reads, so no browser runs the search or the season's transcendental maths:
 *
 *   src/app/site/arc/season.generated.ts       the season's arrays (hydration-exact on every engine)
 *   src/app/site/arc/annotations.generated.ts  every annotation's solved spot
 *
 * Rerun it after changing anything in arc/season.ts, arc/instrument.ts (scales, sizes, MIN_W, minH)
 * or arc/annotate.ts:
 *
 *   npm run arc:precompute     writes both files
 *   npm run arc:check          verifies both files match a fresh build and solve (exit 1 if not)
 *
 * Either mode fails if any label found no clear spot. Needs Node 22.18 or newer (TypeScript type
 * stripping and module.registerHooks), and nothing else: no dependencies.
 */

import { registerHooks } from "node:module";
import { readFileSync, writeFileSync, existsSync } from "node:fs";
import { fileURLToPath } from "node:url";

const ARC = new URL("../src/app/site/arc/", import.meta.url);
const OUT = {
  season: new URL("season.generated.ts", ARC),
  annotations: new URL("annotations.generated.ts", ARC),
};
const check = process.argv.includes("--check");

// The app's imports are extensionless ("./season"): resolve them to the .ts file. The generated
// files are stubbed out, so the season is built live and a stale or missing file never feeds the
// solve that replaces it.
const STUB = {
  "season.generated": "data:text/javascript,export const SEASON_DATA = null;",
  "annotations.generated": "data:text/javascript,export const ANNOTATIONS = [];",
};
registerHooks({
  resolve(specifier, context, next) {
    const fromArc = context.parentURL?.startsWith(ARC.href);
    const name = specifier.replace(/^\.\//, "").replace(/\.ts$/, "");
    if (fromArc && name in STUB) return { url: STUB[name], shortCircuit: true };
    if (fromArc && specifier.startsWith(".") && !/\.[cm]?[jt]sx?$/.test(specifier)) {
      return next(`${specifier}.ts`, context);
    }
    return next(specifier, context);
  },
});

const t0 = performance.now();
const { buildSeason } = await import(new URL("season.ts", ARC).href);
const { solveAnnotations } = await import(new URL("annotate.ts", ARC).href);
const season = buildSeason();
const { annotations, misses } = solveAnnotations();
const ms = performance.now() - t0;

/* ── the files ── */

const HEAD = (what) =>
  `// GENERATED by scripts/arc-precompute.mjs: ${what}. Do not edit by hand.\n` +
  `// Rerun with \`npm run arc:precompute\`; \`npm run arc:check\` verifies it matches a fresh solve.\n\n`;

// JSON prints every number as its shortest round-trip form, so the constants are bit-exact.
const json = (v) => JSON.stringify(v);
const byLift = (rec, indent) =>
  `{\n${Object.entries(rec).map(([k, v]) => `${indent}  ${k}: ${json(v)},`).join("\n")}\n${indent}}`;

function seasonFile(s) {
  const lines = Object.entries(s).map(([k, v]) => {
    if (k === "sessions" || k === "liftDaily") return `  ${k}: ${byLift(v, "  ")},`;
    if (k === "records") return `  ${k}: [\n${v.map((r) => `    ${json(r)},`).join("\n")}\n  ],`;
    return `  ${k}: ${json(v)},`;
  });
  return (
    HEAD("the arc's season, buildSeason() in arc/season.ts") +
    `import type { Season } from "./season";\n\n` +
    `export const SEASON_DATA: Season | null = {\n${lines.join("\n")}\n};\n`
  );
}

function annotationsFile(list) {
  return (
    HEAD("the arc's annotation layout, solveAnnotations() in arc/annotate.ts") +
    `import type { Annotation } from "./instrument";\n\n` +
    `export const ANNOTATIONS: Annotation[] = [\n${list.map((a) => `  ${json(a)},`).join("\n")}\n];\n`
  );
}

const files = [
  [OUT.season, seasonFile(season)],
  [OUT.annotations, annotationsFile(annotations)],
];

/* ── write or verify ── */

let failed = false;
if (misses.length) {
  console.error(`arc: no clear spot for ${misses.join(", ")} (widen MIN_W or move the label)`);
  failed = true;
}
for (const [url, text] of files) {
  const path = fileURLToPath(url);
  const rel = path.slice(path.indexOf("src/"));
  if (check) {
    const same = existsSync(path) && readFileSync(path, "utf8") === text;
    if (!same) {
      console.error(`arc: ${rel} is stale; run npm run arc:precompute`);
      failed = true;
    } else console.log(`arc: ${rel} matches a fresh solve`);
  } else {
    writeFileSync(path, text);
    console.log(`arc: wrote ${rel}`);
  }
}
console.log(`arc: built and solved in ${ms.toFixed(1)} ms (${annotations.length} labels, ${misses.length} misses)`);
if (failed) process.exit(1);
